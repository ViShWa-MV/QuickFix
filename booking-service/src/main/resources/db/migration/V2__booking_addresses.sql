-- The address a customer booked, copied when the booking is made. Later changes to
-- the customer's saved address do not change this copy.
CREATE TABLE IF NOT EXISTS booking_addresses (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id   BIGINT           NOT NULL UNIQUE,
    customer_id  BIGINT           NOT NULL,
    label        VARCHAR(40),
    address_line VARCHAR(200)     NOT NULL,
    locality     VARCHAR(160),
    street_name  VARCHAR(160)     NOT NULL,
    city         VARCHAR(80)      NOT NULL,
    state        VARCHAR(80)      NOT NULL,
    pincode      VARCHAR(6)       NOT NULL,
    latitude     DOUBLE PRECISION,
    longitude    DOUBLE PRECISION,
    created_at   TIMESTAMP        NOT NULL
);
