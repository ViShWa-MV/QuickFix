-- Every post office of every pincode, from the official India Post list.
-- Replaces the single-row table from V2 (no data had been loaded into it yet).
DROP TABLE IF EXISTS pincodes;

CREATE TABLE IF NOT EXISTS pincode_offices (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pincode   VARCHAR(6)   NOT NULL,
    office    VARCHAR(160) NOT NULL,
    district  VARCHAR(120) NOT NULL,
    state     VARCHAR(120) NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_pincode_offices_pincode ON pincode_offices (pincode);
